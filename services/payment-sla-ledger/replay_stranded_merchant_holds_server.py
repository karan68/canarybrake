from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from ledger_ops.remediation import inspect_stranded_merchant_holds
from ledger_ops.remediation import execute_idempotent_v1_replay
from ledger_ops.remediation import issue_sla_recovery_receipt

mcp = FastMCP("replay_stranded_merchant_holds")


@mcp.tool(name="replay_stranded_merchant_holds", description="Inspects stranded merchant holds and, upon confirmation, executes an idempotent v1 replay and issues an SLA recovery receipt.")
def replay_stranded_merchant_holds(merchant_ids_csv: str, confirm: bool) -> dict:
    inspection = inspect_stranded_merchant_holds(merchant_ids_csv)
    if not inspection:
        return {"error": "Failed to inspect stranded merchant holds.", "merchant_ids_csv": merchant_ids_csv}

    if not confirm:
        return {
            "status": "confirmation_required",
            "confirmation_required": True,
            "inspection": inspection,
            "message": "Hold inspection complete. Set confirm=True to execute idempotent v1 replay and issue SLA recovery receipt."
        }

    replay_result = execute_idempotent_v1_replay(merchant_ids_csv)
    if not replay_result:
        return {"error": "Failed to execute idempotent v1 replay.", "merchant_ids_csv": merchant_ids_csv}

    count = replay_result.get("replayed_count", replay_result.get("count", 0))
    amount = replay_result.get("replayed_amount_cents", replay_result.get("amount_cents", 0))

    receipt = issue_sla_recovery_receipt(merchant_ids_csv, count, amount)

    return {
        "status": "success",
        "inspection": inspection,
        "replay_result": replay_result,
        "receipt": receipt
    }


if __name__ == "__main__":
    mcp.run()
